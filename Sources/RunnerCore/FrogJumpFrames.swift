    private static func makeFrame(_ pattern: String) -> RunnerFrame {
        let rows = pattern.split(separator: "\n")
        precondition(rows.count == height)
        precondition(rows.allSatisfy { $0.count == width })

        var pixels = Set<Pixel>()
        for (y, row) in rows.enumerated() {
            for (x, cell) in row.enumerated() where cell == "#" {
                pixels.insert(Pixel(x: x, y: y))
            }
        }

        return RunnerFrame(width: width, height: height, pixels: pixels)
    }
